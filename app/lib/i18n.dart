// 多语言：内置 zh_CN / en_US 翻译

class I18n {
  static const supported = ['zh_CN', 'zh_TW', 'en_US', 'ja_JP'];
  static String current = 'zh_CN';

  static String t(String key) {
    final table = current == 'en_US' ? _en : _zh;
    return table[key] ?? _zh[key] ?? key;
  }

  static void setLocale(String l) {
    current = supported.contains(l) ? l : 'zh_CN';
  }

  // 常用文案
  static String get appName => t('app_name');
  static String get home => t('nav.home');
  static String get resource => t('nav.resource');
  static String get downloads => t('nav.download');
  static String get history => t('nav.history');
  static String get settings => t('nav.settings');
  static String get download => t('action.download');
  static String get cancel => t('action.cancel');
  static String get retry => t('action.retry');
  static String get remove => t('action.remove');
  static String get save => t('action.save');
  static String get search => t('action.search');
  static String get ok => t('action.ok');
}

